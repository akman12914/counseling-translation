export const pickRandom = <T,>(arr: T[]) => arr[Math.floor(Math.random() * arr.length)];
export const getRandomFromCategory = (cat: keyof typeof QA_MAP) => pickRandom(QA_MAP[cat]);

// 🔎 마이크 문장을 카테고리로 매핑하는 간단 규칙
export function matchCategory(utter: string): (keyof typeof QA_MAP) | null {
  const u = utter.replace(/\s+/g, "").toLowerCase();
  const rules: Array<[RegExp, keyof typeof QA_MAP]> = [
    [/눈.*(상담|문의)/, "눈수술_초기상담"],
    [/눈.*(고민|문제|작아|무쌍)/, "눈수술_고민청취"],
    [/눈.*(추천|수술|절개|매몰|교정)/, "눈수술_시술추천"],
    [/눈.*(마무리|최종|3d|시뮬)/, "눈수술_마무리"],

    [/코.*(상담|문의)/, "코수술_초기상담"],
    [/코.*(고민|문제|낮아|매부리|뭉뚝)/, "코수술_고민청취"],
    [/코.*(추천|수술|실리콘|자가|코끝)/, "코수술_시술추천"],
    [/코.*(마무리|최종|3d|시뮬)/, "코수술_마무리"],

    [/(안면|윤곽).*(상담|문의)/, "안면윤곽_초기상담"],
    [/(안면|윤곽).*(고민|문제|사각턱|광대)/, "안면윤곽_고민청취"],
    [/(안면|윤곽).*(추천|수술|턱끝|축소)/, "안면윤곽_시술추천"],
    [/(안면|윤곽).*(마무리|최종|3d|분석)/, "안면윤곽_마무리"],
  ];
  for (const [re, cat] of rules) if (re.test(u)) return cat;
  return null;
}
